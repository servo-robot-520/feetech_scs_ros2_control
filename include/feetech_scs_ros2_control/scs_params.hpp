    struct ScsParamDescriptor {
        /// 配置/接口使用的键名（snake_case）。
        const char* key;
        /// 英文显示名。
        const char* label;
        /// 中文显示名（与官方上位机/内存表一致）。
        const char* zh;
        /// 寄存器起始地址。
        uint8_t address;
        /// 字节宽度。
        ParamWidth width;
        /// 存储区/访问方式。
        ParamAccess access;
        /// 存储区域。
        ParamArea area;
        /// 单位；无单位为空字符串。
        const char* unit;
        /// 最小取值。
        int min;
        /// 最大取值。
        int max;
        /// 枚举取值表（值为索引时给出实际含义）；空为自由取值。
        const int* choices{};
        int choice_count{};
    };

