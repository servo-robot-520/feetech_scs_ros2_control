    /// @brief 参数存储区/访问方式。
    enum class ParamAccess {
        /// 只读。
        kReadOnly,
        /// SRAM，实时可写。
        kRam,
        /// EEPROM，需解锁后写入，掉电保存。
        kEeprom,
    };

    /// @brief 存储区域（显示用，与访问方式正交：只读区也分 EPROM/SRAM/DEFAULT）。
    enum class ParamArea {
        kEeprom,
        kSram,
        kDefault,
    };

    /// @brief 参数字节宽度。
    enum class ParamWidth {
        kByte,
        kWord,
    };

