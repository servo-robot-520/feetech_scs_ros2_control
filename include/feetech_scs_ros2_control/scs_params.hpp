    /// @brief 按键名查找参数描述。
    /// @param key 参数键名。
    /// @return 描述指针；未找到返回 nullptr。
    inline const ScsParamDescriptor* find_parameter(const std::string_view key) {
        for (const auto& descriptor : kParameterDescriptors) {
            if (key == descriptor.key) {
                return &descriptor;
            }
        }
        return nullptr;
    }

